def make_response__temperature(
    coords_to_temperature: dict[tuple[float, float], float],
    least_recorded_temperature: float,
    greatest_recorded_temperature: float,
) -> str:
    """
    Creates a data-populated response for the `temperature` endpoint.

    Args:
        coords_to_temperature: The temperature data.
        least_recorded_temperature: The least recorded temperature.
        greatest_recorded_temperature: The greatest recorded temperature.
    Returns:
        The data response JSON string.
    """
    response = {}

    response["ids"] = [str(key) for key in coords_to_temperature.keys()]
    polys, vals = create_voronoi(
        np.array(list(coords_to_temperature.keys())),
        np.array(list(coords_to_temperature.values())),
        CANADA_BOUNDS,
    )
    response["polygons"] = polys
    response["values"] = vals
    response["valuesLegend"] = {
        "valueRange": (least_recorded_temperature, greatest_recorded_temperature),
        "units": "°C",
        "colourRange": [
            "magenta",
            "blue",
            "green",
            "yellow",
            "red",
        ],
    }
    response["heatStyle"] = {
        "edgeOpacity": 0.2,
    }
    return json_dumps(response)


